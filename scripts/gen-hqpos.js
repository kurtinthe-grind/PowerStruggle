// Generates src/hqpos.ts from the exported map (PS_Isolated.spatial.json): the
// position of each team's HQ (HQ_OBJIDS in src/objids.ts), which a Rorsch
// impact is measured against (nuke.ts, HQ_HIT_RADIUS_M).
//
// Why build time: the HQs are static, and static props have failed to resolve
// at runtime before (gen-navpoints.js). The old HQ_dummy_Target objects
// (7300/7301) were deleted from the map on 2026-10-03; the HQs themselves are
// the targets now.
//
// Re-export the map, then npm run build. A missing HQ fails the build: without
// it the HQ can't be damaged and the match can't be won.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MAP = path.join(ROOT, "PS_Isolated.spatial.json");
const OUT = path.join(ROOT, "src", "hqpos.ts");

function hqIds() {
    const objids = fs.readFileSync(path.join(ROOT, "src", "objids.ts"), "utf8");
    const m = /export const HQ_OBJIDS: number\[\] = \[(\d+), (\d+)\];/.exec(objids);
    if (!m) {
        throw new Error("HQ_OBJIDS not found in src/objids.ts");
    }
    return [Number(m[1]), Number(m[2])];
}

// Every object carrying one of the ids, as { id, name, x, y, z }.
function findHqs(json, ids) {
    const found = [];
    (function walk(o) {
        if (Array.isArray(o)) {
            o.forEach(walk);
            return;
        }
        if (o && typeof o === "object") {
            if (ids.includes(o.ObjId) && o.position) {
                found.push({ id: o.ObjId, name: o.name, x: o.position.x, y: o.position.y, z: o.position.z });
            }
            Object.keys(o).forEach(k => walk(o[k]));
        }
    })(json);
    return ids.map((id, i) => {
        const hits = found.filter(f => f.id === id);
        if (hits.length !== 1) {
            throw new Error("team " + (i + 1) + " HQ: " + hits.length + " objects with ObjId " + id + " (need exactly 1)");
        }
        return hits[0];
    });
}

function render(hqs) {
    const n = (v) => String(Number(v.toFixed(3)));
    return [
        "// GENERATED by scripts/gen-hqpos.js from PS_Isolated.spatial.json. Do not edit.",
        "// x, y, z of the team 1 HQ, then the team 2 HQ.",
        "export const HQ_POS: number[] = [",
        ...hqs.map(h => "    " + [h.x, h.y, h.z].map(n).join(", ") + ", // " + h.id + " " + h.name),
        "];",
        ""
    ].join("\n");
}

function main() {
    const hqs = findHqs(JSON.parse(fs.readFileSync(MAP, "utf8")), hqIds());
    fs.writeFileSync(OUT, render(hqs));
    console.log("hqpos: " + hqs.map(h => h.name + " (" + [h.x, h.y, h.z].map(v => v.toFixed(0)).join(", ") + ")").join(", "));
}

module.exports = { findHqs, render };

if (require.main === module) {
    try {
        main();
    } catch (e) {
        console.error("gen-hqpos FAILED: " + e.message);
        process.exit(1);
    }
}
