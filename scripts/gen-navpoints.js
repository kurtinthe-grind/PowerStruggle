// Generates src/navpoints.ts from the exported map (PS_Isolated.spatial.json):
// every object with an ObjId in the navigation waypoint block, whatever its
// type, as a flat [id, x, y, z, ...] table.
//
// Why build time: in the 2026-10-02 playtest the waypoint props (tiny
// AmmoChest_Small_Int_01, ObjIds 9000-9013) never resolved at runtime -
// mod.GetSpatialObject returned an invalid object for every one of them - so
// bots walked direct. The positions are static map data, so they are read here
// instead and the script needs no lookup at all.
//
// Re-export the map, then npm run build. A missing or unreadable map file
// writes an empty table (botnav then tries the runtime lookup) and warns.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MAP = path.join(ROOT, "PS_Isolated.spatial.json");
const OUT = path.join(ROOT, "src", "navpoints.ts");

// Keep in step with NAV_WAYPOINT_FIRST_ID / NAV_WAYPOINT_LAST_ID in src/objids.ts.
const objids = fs.readFileSync(path.join(ROOT, "src", "objids.ts"), "utf8");
function idConst(name) {
    const m = new RegExp("export const " + name + ": number = (\\d+);").exec(objids);
    if (!m) {
        throw new Error("gen-navpoints: " + name + " not found in src/objids.ts");
    }
    return Number(m[1]);
}
const FIRST = idConst("NAV_WAYPOINT_FIRST_ID");
const LAST = idConst("NAV_WAYPOINT_LAST_ID");

const points = [];
let source = "PS_Isolated.spatial.json";
try {
    const json = JSON.parse(fs.readFileSync(MAP, "utf8"));
    const seen = {};
    (function walk(o) {
        if (Array.isArray(o)) {
            o.forEach(walk);
            return;
        }
        if (o === null || typeof o !== "object") {
            return;
        }
        const id = o.ObjId;
        if (typeof id === "number" && id >= FIRST && id <= LAST && o.position
            && typeof o.position.x === "number") {
            if (seen[id]) {
                console.warn("gen-navpoints: ObjId " + id + " appears twice, keeping the first");
            } else {
                seen[id] = true;
                points.push([id, o.position.x, o.position.y, o.position.z]);
            }
        }
        for (const k of Object.keys(o)) {
            walk(o[k]);
        }
    })(json);
} catch (e) {
    source = "nothing (map file unreadable: " + String(e.message || e).replace(/[\r\n]+/g, " ") + ")";
    console.warn("gen-navpoints: " + source);
}
points.sort((a, b) => a[0] - b[0]);

function num(n) {
    return String(Math.round(n * 1000) / 1000);
}

const lines = [];
lines.push("// GENERATED by scripts/gen-navpoints.js from " + source + " - do not edit.");
lines.push("// Navigation waypoints (ObjId " + FIRST + "-" + LAST + "): id, x, y, z per waypoint.");
lines.push("export const NAV_POINTS: number[] = [");
for (let i = 0; i < points.length; i++) {
    const p = points[i];
    lines.push("    " + p[0] + ", " + num(p[1]) + ", " + num(p[2]) + ", " + num(p[3])
        + (i < points.length - 1 ? "," : ""));
}
lines.push("];");
lines.push("");
const text = lines.join("\n");
const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (old !== text) {
    fs.writeFileSync(OUT, text);
}
console.log("gen-navpoints: " + points.length + " waypoint(s)"
    + (points.length > 0 ? " (ObjId " + points[0][0] + "-" + points[points.length - 1][0] + ")" : ""));
